a = 5 #binary: 0101
b = 2 #binary: 0010

print(a | b) #When comparing two decimal numbers, the | (OR bitwise operator) takes the greatest number of the bit, which is 1
print(a & b) #Similarly, the & (AND bitwise operator) yields a 1 only if both the bits are the same
print(a ^ b) #The ^ (XOR bitwise operator) yields an output of 0 when two bits are the same and 1 when two bits are different
print(a >> b) 
print(a << b)
